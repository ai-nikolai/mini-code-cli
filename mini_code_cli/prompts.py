"""mini_code_cli.prompts -- the templated prompt strings for the agent loop.

This module owns every human-readable prompt template the loop hands to the
model:

  * :func:`system_prompt` -- the top-of-session system prompt (tools, sandbox,
    plan/skills mode).
  * :func:`plan_instructions` -- the extra ``--plan`` mode block.
  * :func:`skills_instructions` -- the ``--skills`` mode block.
  * :func:`compaction_prompt` -- the summarisation request used on history
    compaction.
  * :func:`plan_prompt` -- the generation request used to *author* a plan for
    the current user instruction (see :func:`plan_instructions`).
  * :func:`plan_review_prompt` -- the completion-review request used once the
    work for a request is done, to mark each plan task done / outstanding and
    emit a summary (see :func:`plan_instructions`).
"""

# ---------------------------------------------------------------------------
# the system prompt
# ---------------------------------------------------------------------------

def system_prompt(tools_dict=None, allowed_dir=None, plan_mode=False, skills_dir=None, session_dir=None):
    """
    Takes a list of tool names and returns a system prompt string.

    When ``plan_mode`` is True the prompt also explains that the loop keeps a
    running goal (CURRENT_GOAL.md) and plan (CURRENT_PLAN.md) in the session
    directory (see plan.py) for the human to inspect; the model does not author
    those files itself.
    """

    if tools_dict:
        tool_descriptions = "\n".join([f"{name} : {data['description']}" for name, data in tools_dict.items()])
        base_prompt = "You are a helpful AI assistant with access to the following tools (only):\n"
        end_prompt = (
        "Choose the most appropriate tool for the task at hand. "
        "If a tool fails or you hit a limit, analyze the error and try a different approach. "
        "Be concise and efficient in your tool usage."
        )
    else:
        tool_descriptions = ""
        base_prompt = "You are a helpful AI assistant without any tools."
        end_prompt = ""

        
    allowed_dir_prompt = ""
    if allowed_dir:
        allowed_dir_prompt = f"\nThe path you are allowed to operate in is called: {allowed_dir}"

    skills_prompt = ""
    if skills_dir is not None:
        skills_prompt = "\n" + skills_instructions(skills_dir)

    plan_mode_prompt = ""
    if plan_mode:
        plan_mode_prompt = "\n" + plan_instructions(session_dir)
    
    
    prompt = f"""
{base_prompt}
{tool_descriptions}{end_prompt}{allowed_dir_prompt}{plan_mode_prompt}{skills_prompt}
Important: Follow the user instruction. Do not create additional .md files (unless asked to do so). Do not create unit tests (unless asked to do so), etc.
"""
    return prompt.strip()


def plan_instructions(session_dir=None):
    """The extra system-prompt block appended when ``--plan`` mode is enabled.

    Explains that the loop -- not the agent -- maintains a human-readable plan
    and goal in the session directory (see plan.py): CURRENT_GOAL.md (the
    user's latest instruction) and CURRENT_PLAN.md (an actual, step-by-step
    plan for the current instruction, generated by the loop from the whole
    conversation). After each user request the loop asks the model (with no
    tools) to author that plan, writes it into CURRENT_PLAN.md, and re-sends it
    into the conversation so the model always works from it. Once the model
    predicts no more tool calls, the loop asks it to *review* the plan -- mark
    each task done or outstanding and emit a summary -- writes that summary into
    CURRENT_PLAN.md, re-sends it, and runs one more pass. The model should just
    carry out the work and not try to maintain the files itself (there are no
    tools for it, and they live outside ``--allowed-dir`` anyway).
    """
    where = session_dir if session_dir else "the session directory (in the cache dir)"
    return (
        "PLAN MODE: The loop -- not you -- keeps two human-readable files in the "
        f"session directory ({where}) and maintains them, so they exist for the "
        "human to inspect progress:\n"
        "1. CURRENT_GOAL.md -- the user's latest instruction / goal.\n"
        "2. CURRENT_PLAN.md -- an actual step-by-step plan for the current goal, "
        "which the loop asks you to author (after each request, with no tools) "
        "from the whole conversation, then writes to disk and re-sends to you.\n"
        "The current plan + goal are re-sent to you after any history "
        "compaction so you can always see what you are still working toward.\n"
        "Once you predict no further tool calls, the loop asks you to review the "
        "plan: mark every task done or still outstanding (TODO / IN-PROGRESS), "
        "then emit a one-line summary that is EITHER 'ALL TASKS DONE. Go back to "
        "user.' OR 'TASKS still in progress.' (if any task is outstanding, list "
        "which ones). That summary is written to disk, re-sent to you, and you "
        "run one more pass through the main agent.\n"
        "You do NOT write or edit these files yourself (no tool does, and they "
        "live outside the directory you are allowed to operate in); just carry "
        "out the plan. When asked to produce the plan, output concrete, ordered "
        "steps (markdown numbered list) that accomplish ONLY the current goal."
    )

def skills_instructions(skills_dir):
    """The extra system-prompt block when the skills feature is enabled.

    Tells the agent it has a local ``.mini`` directory of reusable skills and
    explains the skill tools (see :mod:`mini_code_cli.skills`). ``skills_dir``
    is the parent allowed dir; the concrete ``.mini`` path is computed for the
    prompt. The agent must maintain skill files with the scoped
    read_skill_file / write_skill_file tools, which write/read ONLY inside the
    ``.mini`` directory, so skill files always land in the right place.
    """
    from . import skills as skills_mod
    return (
        "SKILLS MODE: You can work with reusable skills kept in the local "
        f".mini directory at: {skills_mod.skills_dir(skills_dir)}.\n"
        "Each skill is a sub-directory containing a `skill.md` (what the skill is "
        "/ how to use it) and optional executable Python helper scripts. There is "
        "also a high-level `SKILLS.md` summary of all skills. All skill files live "
        "inside the ``.mini`` directory above.\n"
        "Use these tools to work with skills:\n"
        "  * `list_skills`  - see which skills exist (name + one-line summary).\n"
        "  * `read_skill`   - read a skill's `skill.md` by name, to learn how to "
        "use it or which scripts it provides.\n"
        "  * `create_skill` - create a new skill (its sub-directory and `skill.md`) "
        "when you build a reusable capability. Give a clear, single-segment name "
        "and a short summary. It is normal to then add Python helper scripts into "
        "the skill's directory. Use the scoped tools below (not the generic "
        "read_file / write_file) so the skill files are written into the ``.mini`` "
        "directory correctly.\n"
        "  * `write_skill_file` - write a file into a skill's directory (e.g. "
        "a new skill's `skill.md` or a helper script), giving its path inside the "
        "``.mini`` directory (e.g. \"my_skill/skill.md\"). This tool is "
        "scoped so it can only write inside the ``.mini`` directory.\n"
        "  * `read_skill_file`  - read a file that already lives inside the "
        "``.mini`` directory (e.g. to check what an existing skill's script "
        "contains). This tool is scoped so it can only read inside ``.mini``.\n"
        "  * `run_skill`    - run one of a skill's Python scripts, passing any "
        "command-line arguments via its `args`. Read the skill first to know "
        "which script to run and what arguments it expects.\n"
        "Prefer turning reusable helpers into skills (with a `skill.md` plus "
        "scripts) so they can be reused later, rather than repeating one-off work.\n"
    )


def compaction_prompt(messages):
    """
    Takes a messages list and returns a compact prompt string summarizing the conversation.
    """
    # .get() rather than msg['content']: a tool-call-only assistant turn has
    # content None (or the key absent) and must not raise KeyError here -- a
    # failed build of the summary prompt would abort the whole compaction.
    conversation = "\n".join(
        [f"{msg.get('role', '?')}: {msg.get('content') or ''}" for msg in messages])
    prompt = f"""
Please analyze the following conversation and output a concise summary covering:
1. Key topics discussed
2. Any decisions made
3. Important information or facts provided
4. Action items or next steps (if any)

Keep the summary to 2-3 sentences.

Conversation:
{conversation}
"""
    return prompt.strip()


def plan_prompt(messages, current_instruction):
    """Build a single-message prompt that asks the model to *author* a plan.

    Like :func:`compaction_prompt`, this is a plain, tool-free request sent to
    the model by the loop (never by the agent). It sends the whole conversation
    transcript plus the current user instruction and asks the model to output a
    concrete, ordered step-by-step plan for accomplishing ONLY that instruction
    (markdown numbered list). This is how the loop generates the actual plan
    written into ``CURRENT_PLAN.md`` (see plan.py) and re-sent into the
    conversation.

    ``messages`` is the full conversation list; ``current_instruction`` is the
    latest user turn.
    """
    # .get() (not msg['content']) for the same reason as compaction_prompt: a
    # tool-call-only assistant turn has no content key, and a KeyError here
    # would silently drop plan-mode authoring for the rest of the session.
    conversation = "\n".join(
        [f"{msg.get('role', '?')}: {msg.get('content') or ''}" for msg in messages])
    prompt = f"""
You are planning how to complete the current user instruction. Using the
full conversation so far, author a concrete, step-by-step plan for accomplishing
ONLY the current instruction below.

Instructions for the plan:
- Output ONLY a numbered list of the steps you still need to take, in order.
- Each step should be specific and actionable (what to run, write, or check).
- Do not summarise the conversation and do not act yet -- just lay out the plan.
- Keep it focused and concise; skip steps that are already done.

Current instruction:
{current_instruction}

Conversation so far:
{conversation}
"""
    return prompt.strip()


def plan_review_prompt(messages, goal):
    """Build the completion-review prompt the loop sends once the work for a
    request looks finished (no further tool calls predicted).

    Like :func:`plan_prompt` and :func:`compaction_prompt`, this is a plain,
    tool-free request sent to the model by the loop -- never by the agent. It
    re-sends the whole conversation so the model can judge what it has actually
    accomplished against ``goal`` and asks it to mark each task of the current
    plan:

      * DONE   -- it has clearly completed it, or
      * TODO   / IN-PROGRESS -- it is still outstanding.

    It then asks the model to emit ONE summary line that is either
    "ALL TASKS DONE. Go back to user." (nothing outstanding) or
    "TASKS still in progress." (listing the outstanding tasks). The loop writes
    this into CURRENT_PLAN.md (see plan.py), re-sends it as a user turn, and
    runs one more pass through the main agent.

    ``messages`` is the full conversation list (used to see what was done);
    ``goal`` is the current user instruction, used as the bar to judge against.
    """
    # .get(): a tool-call-only assistant turn has content None / no key (see
    # compaction_prompt); indexing it here would abort the review.
    conversation = "\n".join(
        [f"{msg.get('role', '?')}: {msg.get('content') or ''}" for msg in messages])
    prompt = f"""
You are reviewing the current plan now that you have (apparently) finished
acting. Using the full conversation so far, decide which tasks of the plan are
done and which are still outstanding.

Mark every task: DONE if you have clearly completed it, or TODO / IN-PROGRESS
if it is still outstanding.

Then output exactly ONE summary line. It must be one of these two, and nothing
else:
- If nothing is outstanding: "ALL TASKS DONE. Go back to user."
- If any task is outstanding: "TASKS still in progress." followed by a short
  list of the tasks still outstanding.

Do not take any action yourself -- only report the plan state.

Be concise in your analysis.

Current goal:
{goal}

Conversation so far:
{conversation}
"""
    return prompt.strip()


