#!/usr/bin/env bash
#
# Schedule the Terminal-Bench SIF preparation job on a CPU Slurm partition.
#
#     scripts/submit_prepare_tb_sifs.sh
#     DRY_RUN=1 SUBMIT=0 scripts/submit_prepare_tb_sifs.sh
#
# The job runs scripts/prepare_tb_sifs.sh: it derives every Terminal-Bench 2.1
# SIF (with the baked mini_code_cli), stages the task set, and verifies the
# images. No GPU is requested; apptainer's 1 GB /tmp is not used.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

# --- edit these -----------------------------------------------------------
JOB_NAME="${JOB_NAME:-tb_sifs}"
WALLTIME="${WALLTIME:-24:00:00}"
PARTITION="${PARTITION:-small}"             # CPU partition (probe: apptainer 1.5.0)
QOS="${QOS:-}"                              # optional
CPUS="${CPUS:-16}"
MEM="${MEM:-64G}"
NODES="${NODES:-1}"

BENCH_ENV="${BENCH_ENV:-hb}"
CONDA_SH="${CONDA_SH:-$HOME/miniconda3/etc/profile.d/conda.sh}"

SIF_CACHE="${SIF_CACHE:-}"                  # empty = repo defaults
TB_STAGED="${TB_STAGED:-experiments/tb-staged}"
TB_TASKS_DIR="${TB_TASKS_DIR:-external_repos/terminal-bench-2-1}"
TB_LIMIT="${TB_LIMIT:-}"                    # empty = all 90 tasks
TB_TASK_IDS="${TB_TASK_IDS:-}"
JOBS="${JOBS:-4}"                           # parallel apptainer builds
FORCE="${FORCE:-0}"
VERIFY="${VERIFY:-inspect}"                 # inspect | test | none

APPTAINER_CACHEDIR="${APPTAINER_CACHEDIR:-$HOME/bench-build/apptainer-cache}"
APPTAINER_TMPDIR="${APPTAINER_TMPDIR:-$HOME/bench-build/apptainer-tmp}"
EXPERIMENTS_DIR="${EXPERIMENTS_DIR:-experiments}"
SUBMIT="${SUBMIT:-1}"                       # 1 = sbatch; 0 = only write
DRY_RUN="${DRY_RUN:-0}"
DEPENDENCY="${DEPENDENCY:-}"                # e.g. afterany:12345 (test job)
# -------------------------------------------------------------------------

die() { printf 'error: %s\n' "$*" >&2; exit 2; }

[[ -d "$TB_TASKS_DIR" ]] || die "TB_TASKS_DIR not found: $TB_TASKS_DIR"
[[ -f "$CONDA_SH" ]] || die "conda.sh not found: $CONDA_SH"

TIMESTAMP="$(date +%Y%m%d_%H%M%S)"
SLURM_DIR="$EXPERIMENTS_DIR/slurm"
LOG_DIR="$EXPERIMENTS_DIR/logs"
mkdir -p "$SLURM_DIR" "$LOG_DIR" "$TB_STAGED" "$APPTAINER_CACHEDIR" "$APPTAINER_TMPDIR"
[[ -n "$SIF_CACHE" ]] && mkdir -p "$SIF_CACHE"

JOB_FILE="$SLURM_DIR/prep_tb_${TIMESTAMP}.sh"
cat <<EOF > "$JOB_FILE"
#!/bin/bash
# Generated by scripts/submit_prepare_tb_sifs.sh -- do not edit by hand.
#SBATCH --job-name=${JOB_NAME}
#SBATCH --output=${LOG_DIR}/${JOB_NAME}_%j.out
#SBATCH --error=${LOG_DIR}/${JOB_NAME}_%j.err
#SBATCH --time=${WALLTIME}
#SBATCH --partition=${PARTITION}
#SBATCH --nodes=${NODES}
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=${CPUS}
#SBATCH --mem=${MEM}
$( [[ -n "$QOS" ]] && echo "#SBATCH --qos=${QOS}" )
$( [[ -n "$DEPENDENCY" ]] && echo "#SBATCH --dependency=${DEPENDENCY}" )

set -uo pipefail
cd $(printf '%q' "$REPO_ROOT")
source $(printf '%q' "$CONDA_SH")
conda activate $(printf '%q' "$BENCH_ENV") || exit 1
mkdir -p $(printf '%q' "$APPTAINER_CACHEDIR") $(printf '%q' "$APPTAINER_TMPDIR")
export APPTAINER_CACHEDIR=$(printf '%q' "$APPTAINER_CACHEDIR")
export APPTAINER_TMPDIR=$(printf '%q' "$APPTAINER_TMPDIR")

echo "host: \$(hostname)  date: \$(date)"
echo "TB tasks: ${TB_TASKS_DIR}"
echo "SIF cache: ${SIF_CACHE:-<repo default>}"
echo "staged: ${TB_STAGED}"
echo "jobs: ${JOBS}  verify: ${VERIFY}"

export BENCH_ENV=$(printf '%q' "$BENCH_ENV")
export CONDA_SH=$(printf '%q' "$CONDA_SH")
export SIF_CACHE=$(printf '%q' "$SIF_CACHE")
export TB_STAGED=$(printf '%q' "$TB_STAGED")
export TB_TASKS_DIR=$(printf '%q' "$TB_TASKS_DIR")
export TB_LIMIT=$(printf '%q' "$TB_LIMIT")
export TB_TASK_IDS=$(printf '%q' "$TB_TASK_IDS")
export JOBS=$(printf '%q' "$JOBS")
export FORCE=$(printf '%q' "$FORCE")
export VERIFY=$(printf '%q' "$VERIFY")

scripts/prepare_tb_sifs.sh
rc=\$?
echo "prepare_tb_sifs exit: \$rc at \$(date)"
exit \$rc
EOF

chmod +x "$JOB_FILE"

echo "=== Terminal-Bench SIF preparation ==="
echo "job file : $JOB_FILE"
echo "partition: $PARTITION  cpus=$CPUS mem=$MEM time=$WALLTIME"
echo "tasks    : ${TB_LIMIT:-all} ${TB_TASK_IDS}"
echo "jobs     : $JOBS  verify=$VERIFY"
echo "SIFs     : ${SIF_CACHE:-<repo default>}"
echo "staged   : $TB_STAGED"
echo "cache    : $APPTAINER_CACHEDIR"
echo "tmp      : $APPTAINER_TMPDIR"
echo "======================================="

if [[ "$DRY_RUN" == "1" || "$SUBMIT" != "1" ]]; then
    echo "not submitting (DRY_RUN=$DRY_RUN SUBMIT=$SUBMIT). Submit with:"
    echo "  sbatch $JOB_FILE"
    exit 0
fi

SUBMITTED="$(sbatch --parsable "$JOB_FILE")"
echo "submitted: $SUBMITTED"
echo "log: $LOG_DIR/${JOB_NAME}_${SUBMITTED}.out"
echo "${SUBMITTED},submitted_prepare_tb,${TIMESTAMP}" >> "$EXPERIMENTS_DIR/submitted.csv"
